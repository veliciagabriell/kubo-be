interface DraftPdfMetadata {
  documentType: string;
  shipmentId: string | null;
  templateVersion: string;
  generatedAt: Date;
  generatedBy: string;
  sources: string[];
}

function safeText(value: unknown): string {
  const printable =
    typeof value === 'string'
      ? value
      : typeof value === 'number' || typeof value === 'boolean'
        ? String(value)
        : '';
  return printable
    .normalize('NFKD')
    .replace(/[^\x20-\x7E]/g, '')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function wrapLine(value: string, width = 92): string[] {
  const words = value.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    if (`${line} ${word}`.trim().length > width && line) {
      lines.push(line);
      line = word;
    } else {
      line = `${line} ${word}`.trim();
    }
  }
  if (line) lines.push(line);
  return lines.length ? lines : ['-'];
}

export function generateDraftPdf(
  title: string,
  fields: Record<string, string>,
  items: Record<string, string>[] | null,
  metadata: DraftPdfMetadata,
): Buffer {
  const lines = [
    'KUBO AI DRAFT - NOT AN OFFICIAL DOCUMENT',
    title.toUpperCase(),
    '',
    `Document type: ${metadata.documentType}`,
    `Shipment: ${metadata.shipmentId ?? '-'}`,
    `Template version: ${metadata.templateVersion}`,
    `Generated at: ${metadata.generatedAt.toISOString()}`,
    `Generated by: ${metadata.generatedBy}`,
    `Sources: ${metadata.sources.join(', ') || '-'}`,
    '',
    'DOCUMENT FIELDS',
    ...Object.entries(fields).flatMap(([key, value]) =>
      wrapLine(`${key}: ${value || '-'}`),
    ),
  ];

  if (items?.length) {
    lines.push('', 'ITEMS');
    items.forEach((item, index) => {
      lines.push(`Item ${index + 1}`);
      Object.entries(item).forEach(([key, value]) =>
        lines.push(...wrapLine(`  ${key}: ${value || '-'}`)),
      );
    });
  }

  lines.push(
    '',
    'AI Draft. Not an official government or carrier-issued document.',
  );
  const pages: string[][] = [];
  for (let index = 0; index < lines.length; index += 48)
    pages.push(lines.slice(index, index + 48));

  const pageCount = pages.length;
  const fontObject = 3 + pageCount * 2;
  const objects: string[] = [];
  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  const pageRefs = pages.map((_, index) => `${3 + index * 2} 0 R`).join(' ');
  objects[2] = `<< /Type /Pages /Kids [${pageRefs}] /Count ${pageCount} >>`;
  pages.forEach((pageLines, index) => {
    const pageObject = 3 + index * 2;
    const contentObject = pageObject + 1;
    const commands = [
      'BT',
      '/F1 10 Tf',
      '14 TL',
      '50 790 Td',
      ...pageLines.flatMap((line, lineIndex) => [
        lineIndex === 0 ? '' : 'T*',
        `(${safeText(line)}) Tj`,
      ]),
      'ET',
    ]
      .filter(Boolean)
      .join('\n');
    objects[pageObject] =
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] ` +
      `/Resources << /Font << /F1 ${fontObject} 0 R >> >> ` +
      `/Contents ${contentObject} 0 R >>`;
    objects[contentObject] =
      `<< /Length ${Buffer.byteLength(commands, 'latin1')} >>\nstream\n${commands}\nendstream`;
  });
  objects[fontObject] =
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';

  let output = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (let index = 1; index < objects.length; index += 1) {
    offsets[index] = Buffer.byteLength(output, 'latin1');
    output += `${index} 0 obj\n${objects[index]}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(output, 'latin1');
  output += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let index = 1; index < objects.length; index += 1)
    output += `${String(offsets[index]).padStart(10, '0')} 00000 n \n`;
  output +=
    `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\n` +
    `startxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(output, 'latin1');
}
